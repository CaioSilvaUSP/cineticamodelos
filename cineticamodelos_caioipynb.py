def fracmolar_para_Xa(xE_array, CA0, CB0):
    """
    Converte fração molar de éster (baseada em A+B+E) em conversão do ácido (Xa).
    """
    xE = np.asarray(xE_array, dtype=float)
    Xa = xE * (CA0 + CB0) / CA0
    return Xa

def calcular_conversao(dados_acido):
    """
    Calcula a conversão Xa em relação ao ácido e retorna um array [tempo, Xa].

    Parâmetro:
      dados_acido : numpy array de duas colunas [tempo, fração molar ácido]

    Retorno:
      numpy array [tempo, Xa]
    """
    C_A0 = dados_acido[0, 1]  # fração inicial do ácido
    Xa = (C_A0 - dados_acido[:, 1]) / C_A0
    return np.column_stack((dados_acido[:, 0], Xa))

def calc_concentracoes_iniciais(r, M_Acido, M_Alcool, rho_Acido, rho_Alcool, BM):
    """
    Calcula as concentrações iniciais (mol/L) do ácido e do álcool
    para uma dada razão molar r = n_alcool/acido.

    Parâmetros:
    r          : razão molar Alcool:Acido
    M_Acido    : massa molar do ácido (g/mol)
    M_Alcool   : massa molar do álcool (g/mol)
    rho_Acido  : densidade do ácido (g/mL)
    rho_Alcool : densidade do álcool (g/mL)
    BM         : base molar (mol de ácido)

    Retorna:
    (C_Alcool, C_Acido) em mol/L
    """
    # Volume total em litros
    V_total_L = ((r * BM * M_Alcool) / rho_Alcool + (BM * M_Acido) / rho_Acido) / 1000.0   # L

    # Concentrações
    C_Alcool = (r * BM)/ V_total_L     #mol/L
    C_Acido = (BM) / V_total_L   # mol/L

    return C_Alcool, C_Acido

def ajustar_modelo_irreversivel(data_exp, C0, ce_exp, t_span, t_eval,
                                guess=[0.001], bounds=[(1e-6, 10)]):
    """
    Ajusta o parâmetro k (2ª ordem irreversível) do modelo de esterificação
    com proporção 1:1 (ácido acrílico + 2-etil-hexanol).
    Baseado em Komon et al. (2012).
    """

    # ------------------------------
    # Modelo EDO irreversível
    # ------------------------------
    def model(t, C, k):
        CA, CB, CE, CW = C
        ra = k * CA * CB  # sem termo de equilíbrio
        return [-ra, -ra, ra, ra]

    # ------------------------------
    # Função objetivo (RMSE)
    # ------------------------------
    def objective(params):
        (k,) = params
        sol = solve_ivp(model, t_span, C0, args=(k,),
                        t_eval=data_exp[:, 0], method='RK45')
        ce_model = sol.y[2]
        rmse = np.sqrt(np.mean((ce_model - ce_exp) ** 2))
        return rmse

    # ------------------------------
    # Otimização
    # ------------------------------
    result = minimize(objective, guess, bounds=bounds, method='L-BFGS-B')
    best_k = result.x[0]

    # ------------------------------
    # Simulação final
    # ------------------------------
    sol = solve_ivp(model, t_span, C0, args=(best_k,),
                    t_eval=t_eval, method='RK45')

    # Interpolação nos pontos experimentais para calcular R²
    sol_interp = solve_ivp(model, t_span, C0, args=(best_k,),
                           t_eval=data_exp[:, 0], method='RK45')
    ce_sim = sol_interp.y[2]
    r2 = r2_score(ce_exp, ce_sim)

    # ------------------------------
    # Plotagem
    # ------------------------------
    plt.figure(figsize=(10, 6))
    plt.plot(sol.t, sol.y[2], label='CE (simulado)', linewidth=2)
    plt.scatter(data_exp[:, 0], ce_exp, color='red', label='CE (experimental)', zorder=5)

    plt.xlabel('Tempo (s)')
    plt.ylabel('Concentração (mol/L)')
    plt.title(f'Ajuste do Modelo Irreversível\nk = {best_k:.6f}, R² = {r2:.4f}')
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

    # ------------------------------
    # Resultados
    # ------------------------------
    print(f"Melhor k: {best_k:.6f} L/(mol·s)")
    print(f"Coeficiente de Determinação R²: {r2:.4f}")

    return {
        "k": best_k,
        "R2": r2,
        "t_sim": sol.t,
        "CE_sim": sol.y[2],
        "CE_exp": data_exp[:, 1],
        "tempo_exp": data_exp[:, 0]
    }

def pseudo_estado_estacionario(dados, label, CA0, CB0, Ccat=0.26,guess=0.001):
    """
    Ajusta kd pelo modelo de pseudo-estado estacionário (Keq fixo do equilíbrio) para função de esterificação com proporção 1:1.
    Agora inclui a plotagem do ajuste.
    """

    # Extrai tempo e conversão experimental
    t_exp = dados[:, 0]
    Xa_exp = dados[:, 1]
    CE_exp = Xa_exp * CA0

    # Condições iniciais
    C0 = [CA0, CB0, 0.0, 0.0]

    # Modelo cinético
    def model(t, C, kd, Keq):
        CA, CB, CE, CW = C
        ra = float(kd * ((CA * CB) - (CE * CW)/Keq))
        return np.array([-ra, -ra, ra, ra])

    # -------------------------------
    # Calcular Keq do equilíbrio experimental
    # -------------------------------
    CE_eq = CE_exp[-1]
    CW_eq = CE_eq
    CA_eq = CA0 - CE_eq
    CB_eq = CB0 - CE_eq
    Keq = (CE_eq * CW_eq) / (CA_eq * CB_eq)
    print(f"Keq (do equilíbrio) = {Keq:.6f}")

    # -------------------------------
    # Ajuste de kd (Keq fixo)
    # -------------------------------
    def objective_kd(kd):
        sol = solve_ivp(model, [0, max(t_exp)], C0, args=(kd, Keq), t_eval=t_exp)
        CE_model = sol.y[2]
        return np.sqrt(np.mean((CE_model - CE_exp) ** 2))

    result_kd = minimize(objective_kd, [guess], bounds=[(1e-5, 1)], method='L-BFGS-B')
    kd = result_kd.x[0]
    print(f"kd ajustado = {kd:.6f} L²/mol²·min")

    # -------------------------------
    # Simulação final


    # -------------------------------
    t_sim = np.linspace(0, max(t_exp), 300)
    sol = solve_ivp(model, [0, max(t_exp)], C0, args=(kd, Keq), t_eval=t_sim)
    Xa_sim = (CA0 - sol.y[0]) / CA0

    # -------------------------------
    # R² do ajuste
    # -------------------------------
    sol_exp = solve_ivp(model, [0, max(t_exp)], C0, args=(kd, Keq), t_eval=t_exp)
    r2 = r2_score(CE_exp, sol_exp.y[2])

    # -------------------------------
    # Plotagem
    # -------------------------------
    plt.figure(figsize=(10, 6))
    plt.plot(t_sim, sol.y[2], label='CE (simulado)', linewidth=2)
    plt.scatter(t_exp, CE_exp, color='red', label='CE (experimental)', zorder=5)

    plt.xlabel('Tempo (min)')
    plt.ylabel('Concentração (mol/L)')
    plt.title(f'{label}\nkd = {kd:.6f}, Keq = {Keq:.6f}, R² = {r2:.4f}')
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

    # -------------------------------
    # Resultados
    # -------------------------------
    print(f"\n>>> {label}")
    print(f"CA0  = {CA0:.3f} mol/L")
    print(f"kd   = {kd:.6f} L²/mol²·min")
    print(f"Keq  = {Keq:.6f}")
    print(f"R²   = {r2:.4f}")

    return t_sim, sol.y[2], Xa_sim, t_exp, CE_exp, Xa_exp, kd, Keq

