import numpy as np
import matplotlib.pyplot as plt
from scipy.optimize import minimize
from scipy.integrate import solve_ivp
from sklearn.metrics import r2_score

def ajustar_modelo(data_exp, C0, ce_exp, t_span, t_eval, guess=[0.001, 1], bounds=[(1e-5, 1), (0.1, 10)]):
    """
    Ajusta parâmetros kd e Keq do modelo de esterificação com proporção 1:1.
    Agora inclui a plotagem do ajuste e melhorias no diagnóstico.
    """

    # ------------------------------
    # Modelo EDO
    # ------------------------------
    def model(t, C, kd, Keq):
        CA, CB, CE, CW = C
        ra = kd * ((CA * CB - CE * CW) / Keq)
        return [-ra, -ra, ra, ra]

    # ------------------------------
    # Função objetivo (RMSE)
    # ------------------------------
    def objective(params):
        kd, Keq = params
        sol = solve_ivp(model, t_span, C0, args=(kd, Keq),
                        t_eval=data_exp[:, 0], method='RK45')

        # Verificação para lidar com possíveis falhas na integração
        if not sol.success:
            print(f"Atenção: solve_ivp falhou com kd={kd:.6f}, Keq={Keq:.6f}. Mensagem: {sol.message}")
            return np.inf  # Retorna infinito para penalizar o otimizador

        ce_model = sol.y[2]
        rmse = np.sqrt(np.mean((ce_model - ce_exp) ** 2))

        # Imprime informações de depuração para acompanhar a otimização
        print(f"Tentando kd={kd:.6f}, Keq={Keq:.6f} -> RMSE={rmse:.6f}")

        return rmse

    # ------------------------------
    # Otimização
    # ------------------------------
    print("Iniciando a otimização...")
    result = minimize(objective, guess, bounds=bounds, method='L-BFGS-B')

    if not result.success:
        print("\nAVISO: A otimização não foi bem-sucedida.")
        print(f"Mensagem do otimizador: {result.message}")
    else:
        print("\nOtimização concluída com sucesso!")

    best_kd, best_Keq = result.x
    final_rmse = result.fun

    # ------------------------------
    # Simulação final
    # ------------------------------
    sol = solve_ivp(model, t_span, C0, args=(best_kd, best_Keq),
                    t_eval=t_eval, method='RK45')

    # Interpolação nos pontos experimentais para calcular R²
    sol_interp = solve_ivp(model, t_span, C0, args=(best_kd, best_Keq),
                            t_eval=data_exp[:, 0], method='RK45')
    ce_sim = sol_interp.y[2]
    r2 = r2_score(ce_exp, ce_sim)

    # ------------------------------
    # Plotagem
    # ------------------------------
    plt.figure(figsize=(10, 6))
    plt.plot(sol.t, sol.y[2], label='CE (simulado)', linewidth=2)
    plt.scatter(data_exp[:, 0], ce_exp, color='red', label='CE (experimental)', zorder=5)

    plt.xlabel('Tempo (segundos)')
    plt.ylabel('Concentração (mol/L)')
    plt.title(f'Ajuste do Modelo\nkd = {best_kd:.6f}, Keq = {best_Keq:.6f}, R² = {r2:.4f}, RMSE = {final_rmse:.6f}')
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

    # ------------------------------
    # Resultados
    # ------------------------------
    print(f"\nMelhor kd: {best_kd:.6f}")
    print(f"Melhor Keq: {best_Keq:.6f}")
    print(f"Coeficiente de Determinação R²: {r2:.4f}")
    print(f"Erro Quadrático Médio (RMSE) final: {final_rmse:.6f}")

    return {
        "kd": best_kd,
        "Keq": best_Keq,
        "R2": r2,
        "t_sim": sol.t,
        "CE_sim": sol.y[2],
        "CE_exp": data_exp[:, 1],
        "tempo_exp": data_exp[:, 0]
    }