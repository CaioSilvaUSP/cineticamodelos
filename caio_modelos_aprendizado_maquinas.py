def treinar_rede_neural_complexa(
    X, y,
    test_size=0.32,
    learning_rate=0.001,
    epochs=350,
    batch_size=10,
    verbose_interval=10
):

    # Divisão dos dados
    X_train, X_test, y_train, y_test = train_test_split(
        X, y, test_size=test_size, random_state=42
    )

    # Normalização
    scaler_X = StandardScaler()
    X_train_scaled = scaler_X.fit_transform(X_train)
    X_test_scaled = scaler_X.transform(X_test)

    scaler_y = StandardScaler()
    y_train_scaled = scaler_y.fit_transform(y_train.reshape(-1, 1))
    y_test_scaled = scaler_y.transform(y_test.reshape(-1, 1))

    # Modelo
    model = Sequential([
        Input(shape=(X_train_scaled.shape[1],)),
        Dense(128, activation="relu"),
        Dense(52, activation="relu"),
        Dense(52, activation="relu"),
        Dense(52, activation="relu"),
        Dense(52, activation="sigmoid"),
        Dropout(0.2),
        Dense(1, activation="linear")
    ])

    model.compile(
        optimizer=Adam(learning_rate=learning_rate),
        loss="mean_squared_error"
    )

    # Listas de histórico
    loss_train_list = []
    loss_val_list = []
    r2_train_list = []
    r2_test_list = []

    # Loop de treinamento manual
    for epoch in range(epochs):

        history = model.fit(
            X_train_scaled, y_train_scaled,
            epochs=1,
            batch_size=batch_size,
            verbose=0,
            validation_data=(X_test_scaled, y_test_scaled)
        )

        loss_train_list.append(history.history["loss"][0])
        loss_val_list.append(history.history["val_loss"][0])

        # Previsões em escala original
        y_train_pred_scaled = model.predict(X_train_scaled, verbose=0)
        y_test_pred_scaled = model.predict(X_test_scaled, verbose=0)

        y_train_pred = scaler_y.inverse_transform(y_train_pred_scaled)
        y_test_pred = scaler_y.inverse_transform(y_test_pred_scaled)

        # Métricas
        r2_train = r2_score(y_train, y_train_pred)
        r2_test = r2_score(y_test, y_test_pred)

        r2_train_list.append(r2_train)
        r2_test_list.append(r2_test)

        if (epoch + 1) % verbose_interval == 0 or epoch == 0:
            print(
                f"Epoca {epoch+1}/{epochs}  "
                f"Loss treino {loss_train_list[-1]:.4f}  "
                f"Loss val {loss_val_list[-1]:.4f}  "
                f"R2 treino {r2_train:.4f}  "
                f"R2 val {r2_test:.4f}"
            )

    # Métricas finais
    rmse_train = np.sqrt(mean_squared_error(y_train, y_train_pred))
    rmse_test = np.sqrt(mean_squared_error(y_test, y_test_pred))

    resultados = {
        "modelo": model,
        "scaler_X": scaler_X,
        "scaler_y": scaler_y,
        "y_train_pred": y_train_pred,
        "y_test_pred": y_test_pred,
        "r2_train": r2_train,
        "r2_test": r2_test,
        "rmse_train": rmse_train,
        "rmse_test": rmse_test,
        "loss_train_list": loss_train_list,
        "loss_val_list": loss_val_list,
        "r2_train_list": r2_train_list,
        "r2_test_list": r2_test_list
    }

    # Plot final
    plt.figure(figsize=(12, 6))

    plt.subplot(1, 2, 1)
    plt.plot(loss_train_list, label="Loss Treino")
    plt.plot(loss_val_list, label="Loss Validacao")
    plt.title("Evolucao do Loss")
    plt.xlabel("Epocas")
    plt.ylabel("Loss MSE")
    plt.legend()
    plt.grid(True)

    plt.subplot(1, 2, 2)
    plt.plot(r2_train_list, label="R2 Treino")
    plt.plot(r2_test_list, label="R2 Validacao")
    plt.title("Evolucao do R2")
    plt.xlabel("Epocas")
    plt.ylabel("R2")
    plt.legend()
    plt.grid(True)

    plt.tight_layout()
    plt.show()

    return resultados

