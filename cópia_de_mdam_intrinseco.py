def modelo_arvores_com_validacao(
    X,
    Y,
    metodo="extratrees",  # opções: "extratrees", "randomforest", "gradientboost", "catboost"
    test_size=0.3,
    random_state=42,
    n_estimators=300,
    n_jobs=-1,
    plotar_graficos=True
):
    import numpy as np
    import pandas as pd
    import matplotlib.pyplot as plt
    from sklearn.model_selection import train_test_split
    from sklearn.metrics import r2_score, mean_squared_error
    from sklearn.ensemble import ExtraTreesRegressor, RandomForestRegressor, GradientBoostingRegressor
    from catboost import CatBoostRegressor

    # ======================================================
    # 1) SPLIT
    # ======================================================
    X_treino, X_teste, Y_treino, Y_teste = train_test_split(
        X, Y, test_size=test_size, random_state=random_state
    )

    # ======================================================
    # 2) DEFINIÇÃO DO MODELO
    # ======================================================
    metodo = metodo.lower()
    if metodo == "extratrees":
        modelo = ExtraTreesRegressor(n_estimators=n_estimators, random_state=random_state, n_jobs=n_jobs)
    elif metodo == "randomforest":
        modelo = RandomForestRegressor(n_estimators=n_estimators, random_state=random_state, n_jobs=n_jobs)
    elif metodo == "gradientboost":
        modelo = GradientBoostingRegressor(n_estimators=n_estimators, random_state=random_state)
    elif metodo == "catboost":
        modelo = CatBoostRegressor(
            iterations=n_estimators,
            random_state=random_state,
            verbose=False,
            thread_count=n_jobs
        )
    else:
        raise ValueError("Método inválido. Use 'extratrees', 'randomforest', 'gradientboost' ou 'catboost'.")

    modelo.fit(X_treino, Y_treino.to_numpy().ravel())

    # ======================================================
    # 3) MÉTRICAS
    # ======================================================
    Y_pred_treino = modelo.predict(X_treino)
    Y_pred_teste = modelo.predict(X_teste)

    r2_train = r2_score(Y_treino, Y_pred_treino)
    rmse_train = np.sqrt(mean_squared_error(Y_treino, Y_pred_treino))
    r2_test = r2_score(Y_teste, Y_pred_teste)
    rmse_test = np.sqrt(mean_squared_error(Y_teste, Y_pred_teste))

    print("\n========== MÉTRICAS ==========")
    print(f"Treino  - R²: {r2_train:.4f} | RMSE: {rmse_train:.4f}")
    print(f"Teste   - R²: {r2_test:.4f} | RMSE: {rmse_test:.4f}")

    # ======================================================
    # 4) GRÁFICOS
    # ======================================================
    if plotar_graficos:
        for Y_real, Y_pred, label in zip([Y_treino, Y_teste], [Y_pred_treino, Y_pred_teste], ["Treino", "Teste"]):
            plt.figure()
            plt.scatter(Y_real, Y_pred)
            plt.plot([Y_real.min(), Y_real.max()], [Y_real.min(), Y_real.max()])
            plt.xlabel("Real")
            plt.ylabel("Predito")
            plt.title(label)
            plt.grid(True)
            plt.show()

    # ======================================================
    # 5) VALIDAÇÃO ARRHENIUS
    # ======================================================
    print("\n========== VALIDAÇÃO ARRHENIUS ==========")

    temperaturas = np.array([351.15, 356.15, 361.15, 366.15])
    viscosidades = np.array([0.5163272932, 0.4932437954, 0.4717894062, 0.4518166304])

    ks = []
    for T, visc in zip(temperaturas, viscosidades):
        dados = {
            'T (K)': [T],
            '% Cat': [9.36], # Retirado de interpolação
            'RM (alcool/acid)': [5],
            'N° Carbonos': [4],  # Isobutanol
            'Volume molar (cm3/mol)': [83.937],
            'Diam molec': [0.51],
            'N° Carbonos.1': [2],  # Acido Acetico
            'Volume molar': [57.35],
            'Diam molec.1': [0.44],
            'Viscosidade': [visc],
            'CTI (meq/g)': [4.81]
        }
        X_pred = pd.DataFrame(dados)
        k_pred = modelo.predict(X_pred)
        ks.append(float(k_pred[0]))

    ks = np.array(ks)
    monotonicidade = np.all(np.diff(ks) > 0)

    if np.any(ks <= 0):
        print("Erro: k negativo")
        return

    invT = 1 / temperaturas
    lnk = np.log(ks)
    slope, intercept = np.polyfit(invT, lnk, 1)
    Ea = -slope * 8.314
    lnk_pred = slope * invT + intercept
    SS_res = np.sum((lnk - lnk_pred)**2)
    SS_tot = np.sum((lnk - np.mean(lnk))**2)
    R2_arr = 1 - SS_res / SS_tot

    plt.figure()
    plt.plot(invT, lnk, 'o')
    plt.plot(invT, lnk_pred)
    plt.xlabel("1/T")
    plt.ylabel("ln(k)")
    plt.grid(True)
    plt.show()

    print("k previstos:", ks)
    print("Monotonicidade:", monotonicidade)
    print(f"Ea aparente = {Ea:.2f} J/mol")
    print(f"R² Arrhenius = {R2_arr:.5f}")

    coerente = (monotonicidade and 10000 < Ea < 120000 and R2_arr > 0.95)
    print("Modelo fisicamente coerente:", coerente)

    return {
        "modelo": modelo,
        "metricas": {"r2_train": r2_train, "r2_test": r2_test, "rmse_train": rmse_train, "rmse_test": rmse_test},
        "arrhenius": {"Ea": Ea, "R2": R2_arr, "monotonicidade": monotonicidade, "coerente": coerente}
    }



