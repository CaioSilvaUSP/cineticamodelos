def treinar_rede_neural_fisicamente_assistida(
    X,
    y,
    test_size=0.36,
    random_state=35
):

    import numpy as np
    import matplotlib.pyplot as plt
    from sklearn.model_selection import train_test_split
    from sklearn.preprocessing import StandardScaler
    from sklearn.metrics import r2_score, mean_squared_error
    import tensorflow as tf
    from tensorflow.keras.models import Sequential
    from tensorflow.keras.layers import Dense, Input
    from tensorflow.keras.optimizers import Adam
    from tensorflow.keras.callbacks import EarlyStopping

    # ===============================
    # FUNÇÃO RMSE
    # ===============================

    def rmse_loss(y_true, y_pred):
        return tf.sqrt(tf.reduce_mean(tf.square(y_pred - y_true)))

    # ===============================
    # 1) Transformação física
    # ===============================

    X = X.copy()
    X["1/T"] = 1 / X["T (K)"]

    y_log = np.log(y)

    # ===============================
    # 2) Split
    # ===============================

    X_train, X_test, y_train, y_test = train_test_split(
        X, y_log, test_size=test_size, random_state=random_state
    )

    # ===============================
    # 3) Normalização
    # ===============================

    scaler_X = StandardScaler()
    X_train_scaled = scaler_X.fit_transform(X_train)
    X_test_scaled = scaler_X.transform(X_test)

    scaler_y = StandardScaler()
    y_train_scaled = scaler_y.fit_transform(y_train.reshape(-1, 1))
    y_test_scaled = scaler_y.transform(y_test.reshape(-1, 1))

    # ===============================
    # 4) Arquitetura
    # ===============================

    model = Sequential([
        Input(shape=(X_train_scaled.shape[1],)),
        Dense(16, activation="relu"),
        Dense(16, activation="relu"),
        Dense(1, activation="linear")
    ])

    model.compile(
        optimizer=Adam(learning_rate=0.001),
        loss=rmse_loss
    )

    early_stop = EarlyStopping(
        monitor="val_loss",
        patience=40,
        restore_best_weights=True
    )

    history = model.fit(
        X_train_scaled,
        y_train_scaled,
        validation_data=(X_test_scaled, y_test_scaled),
        epochs=600,
        batch_size=8,
        callbacks=[early_stop],
        verbose=0
    )

    # ===============================
    # 5) Avaliação estatística
    # ===============================

    y_train_pred_log = scaler_y.inverse_transform(
        model.predict(X_train_scaled, verbose=0)
    ).flatten()

    y_test_pred_log = scaler_y.inverse_transform(
        model.predict(X_test_scaled, verbose=0)
    ).flatten()

    r2_train = r2_score(y_train, y_train_pred_log)
    r2_test = r2_score(y_test, y_test_pred_log)

    rmse_train = np.sqrt(mean_squared_error(y_train, y_train_pred_log))
    rmse_test = np.sqrt(mean_squared_error(y_test, y_test_pred_log))

    print("\n===== MÉTRICAS EM ln(k) =====")
    print("R2 treino:", round(r2_train, 4))
    print("R2 teste :", round(r2_test, 4))
    print("RMSE treino:", round(rmse_train, 4))
    print("RMSE teste :", round(rmse_test, 4))

    # ===============================
    # 6) Curva de aprendizado
    # ===============================

    plt.figure()
    plt.plot(history.history["loss"])
    plt.plot(history.history["val_loss"])
    plt.xlabel("Épocas")
    plt.ylabel("RMSE")
    plt.grid(True)
    plt.show()

    return model, scaler_X, scaler_y

