def modelo_arvores_arrhenius(
    X,
    y,
    metodo="extratrees",
    test_size=0.3,
    random_state=42,
    n_estimators=300,
    n_jobs=-1
):

    import numpy as np
    import pandas as pd
    import matplotlib.pyplot as plt
    from sklearn.model_selection import train_test_split
    from sklearn.metrics import r2_score, mean_squared_error
    from sklearn.ensemble import ExtraTreesRegressor, RandomForestRegressor, GradientBoostingRegressor
    from catboost import CatBoostRegressor

    # ======================================================
    # 1) TRANSFORMAÇÃO ARRHENIUS
    # ======================================================
    X = X.copy()
    X["1/T"] = 1 / X["T (K)"]

    y_log = np.log(y)

    # ======================================================
    # 2) SPLIT
    # ======================================================
    X_treino, X_teste, y_treino, y_teste = train_test_split(
        X, y_log, test_size=test_size, random_state=random_state
    )

    # ======================================================
    # 3) MODELO
    # ======================================================
    metodo = metodo.lower()

    if metodo == "extratrees":
        modelo = ExtraTreesRegressor(
            n_estimators=n_estimators,
            random_state=random_state,
            n_jobs=n_jobs
        )

    elif metodo == "randomforest":
        modelo = RandomForestRegressor(
            n_estimators=n_estimators,
            random_state=random_state,
            n_jobs=n_jobs
        )

    elif metodo == "gradientboost":
        modelo = GradientBoostingRegressor(
            n_estimators=n_estimators,
            random_state=random_state
        )

    elif metodo == "catboost":
        modelo = CatBoostRegressor(
            iterations=n_estimators,
            random_state=random_state,
            verbose=False,
            thread_count=n_jobs
        )

    else:
        raise ValueError("Método inválido")

    modelo.fit(X_treino, y_treino)

    # ======================================================
    # 4) PREDIÇÃO
    # ======================================================
    y_pred_treino = modelo.predict(X_treino)
    y_pred_teste = modelo.predict(X_teste)

    # ======================================================
    # 5) MÉTRICAS (em ln(k))
    # ======================================================
    r2_train = r2_score(y_treino, y_pred_treino)
    rmse_train = np.sqrt(mean_squared_error(y_treino, y_pred_treino))

    r2_test = r2_score(y_teste, y_pred_teste)
    rmse_test = np.sqrt(mean_squared_error(y_teste, y_pred_teste))

    print("\n===== ARRHENIUS MODEL =====")
    print(f"Treino  - R²: {r2_train:.4f} | RMSE: {rmse_train:.4f}")
    print(f"Teste   - R²: {r2_test:.4f} | RMSE: {rmse_test:.4f}")

    # ======================================================
    # 6) GRÁFICO ARRHENIUS (O MAIS IMPORTANTE)
    # ======================================================
    plt.figure()

    # Real
    plt.scatter(X["1/T"], y_log, label="Real", alpha=0.7)

    # Predito (todos os pontos)
    y_pred_total = modelo.predict(X)
    plt.scatter(X["1/T"], y_pred_total, label="Predito", alpha=0.7)

    plt.xlabel("1/T (1/K)")
    plt.ylabel("ln(k)")
    plt.legend()
    plt.grid(True)

    plt.show()

    return modelo



