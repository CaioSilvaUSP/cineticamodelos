def treinar_rede_neural_3fold(
    X,
    y,
    random_state=35
):

    X = X.copy()
    X["1/T"] = 1 / X["T (K)"]
    y_log = np.log(y)

    rkf = RepeatedKFold(
        n_splits=3,
        n_repeats=1,
        random_state=random_state
    )

    r2_scores = []
    rmse_scores = []

    fold = 1

    for train_idx, test_idx in rkf.split(X):

        print(f"\n===== FOLD {fold} =====")

        X_train, X_test = X.iloc[train_idx], X.iloc[test_idx]
        y_train, y_test = y_log[train_idx], y_log[test_idx]

        # ===============================
        # Normalização (sem vazamento)
        # ===============================
        scaler_X = StandardScaler()
        X_train_scaled = scaler_X.fit_transform(X_train)
        X_test_scaled = scaler_X.transform(X_test)

        scaler_y = StandardScaler()
        y_train_scaled = scaler_y.fit_transform(y_train.reshape(-1, 1))

        # ===============================
        # Modelo
        # ===============================
        model = Sequential([
            Input(shape=(X_train_scaled.shape[1],)),
            Dense(16, activation="relu"),
            Dense(16, activation="relu"),
            Dense(1, activation="linear")
        ])

        model.compile(
            optimizer=Adam(learning_rate=0.001),
            loss="mse"
        )

        early_stop = EarlyStopping(
            monitor="val_loss",
            patience=40,
            restore_best_weights=True
        )

        # ===============================
        # Treinamento
        # ===============================
        model.fit(
            X_train_scaled,
            y_train_scaled,
            validation_split=0.2,
            epochs=600,
            batch_size=8,
            callbacks=[early_stop],
            verbose=0
        )

        # ===============================
        # Predição
        # ===============================
        y_pred = scaler_y.inverse_transform(
            model.predict(X_test_scaled, verbose=0)
        ).flatten()

        # ===============================
        # Métricas
        # ===============================
        r2 = r2_score(y_test, y_pred)
        rmse = np.sqrt(mean_squared_error(y_test, y_pred))

        print("R2:", round(r2, 4))
        print("RMSE:", round(rmse, 4))

        r2_scores.append(r2)
        rmse_scores.append(rmse)

        fold += 1

    # ===============================
    # Resultado final
    # ===============================
    print("\n===== RESULTADO FINAL =====")
    print("R2 médio :", round(np.mean(r2_scores), 4))
    print("R2 std   :", round(np.std(r2_scores), 4))
    print("RMSE médio:", round(np.mean(rmse_scores), 4))
    print("RMSE std  :", round(np.std(rmse_scores), 4))

    return r2_scores, rmse_scores

